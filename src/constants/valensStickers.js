/**
 * Search and filter helper
 * @param {string} query - text input from search bar
 * @param {string} category - active category filter key
 * @returns {Array} matching stickers list
 */
export function filterStickers(query = '', category = 'all') {
  const cleanQuery = (query || '').toLowerCase().trim();

  // If viewing emojis category
  if (category === 'emojis') {
    if (!cleanQuery) return POPULAR_EMOJIS.map(e => ({ id: `emoji_${e}`, type: 'emoji', emoji: e }));
    return POPULAR_EMOJIS
      .filter(e => e.includes(cleanQuery))
      .map(e => ({ id: `emoji_${e}`, type: 'emoji', emoji: e }));
  }

  // Combine items according to category
  let pool = [];
  if (category === 'all') {
    pool = [
      ...DRALENS_STICKERS.map(d => ({ ...d, type: 'svg' })),
      ...VALENS_STICKERS.map(v => ({ ...v, type: 'image' })),
    ];
  } else if (category === 'dralens') {
    pool = DRALENS_STICKERS.map(d => ({ ...d, type: 'svg' }));
  } else {
    pool = VALENS_STICKERS.filter(v => v.pack === category).map(v => ({ ...v, type: 'image' }));
  }

  if (!cleanQuery) {
    return pool;
  }

  // Search by query
  return pool.filter(item => {
    if (item.title && item.title.toLowerCase().includes(cleanQuery)) return true;
    if (item.name && item.name.toLowerCase().includes(cleanQuery)) return true;
    if (item.emoji && item.emoji.includes(cleanQuery)) return true;
    if (item.keywords && item.keywords.some(k => k.toLowerCase().includes(cleanQuery))) return true;
    return false;
  });
}
